export const TANZANIA_REGION_LIST: readonly string[] = Object.keys(
  TANZANIA_REGION_DISTRICTS,
).sort()

export function getDistrictsForRegion(region: string): readonly string[] {
  if (!region) return []
  return TANZANIA_REGION_DISTRICTS[region] ?? []
}

export function isValidDistrictForRegion(
  region: string,
  district: string,
): boolean {
  if (!region || !district) return false
  const list = TANZANIA_REGION_DISTRICTS[region]
  return Boolean(list && list.includes(district))
}
